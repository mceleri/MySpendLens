def normalize(name: str) -> str:
    cleaned = re.sub(r"[^A-Z0-9\s]", " ", name.upper())
    return re.sub(r"\s+", " ", cleaned).strip()


def truncate_vowels(name: str) -> str:
    """Realistic bank statement vowel removal / truncation for n-gram training."""
    tokens = name.split()
    out = []
    for tok in tokens:
        if len(tok) <= 3 or tok.isdigit():
            out.append(tok)
        else:
            # Keep leading letters + strip interior vowels (e.g. ESSELUNGA -> ESSLNG, MERCADONA -> MRCDN)
            prefix_keep = 2 if tok[0] in "AEIOU" and len(tok) >= 6 else 1
            stripped = tok[:prefix_keep] + re.sub(r"[AEIOU]", "", tok[prefix_keep:])
            if len(stripped) < 3:
                stripped = tok[:3]
            out.append(stripped[:8])
    return " ".join(out)


def truncate_prefix_slice(name: str) -> str:
    """Realistic character-limit truncation / consonant compression."""
    tokens = name.split()
    out = []
    for idx, tok in enumerate(tokens):
        if len(tok) <= 3 or tok.isdigit():
            out.append(tok[0] if idx == 0 and len(tok) == 2 and len(tokens) > 1 else tok)
        else:
            # Keep final vowel or consonant cluster (e.g. ESSELUNGA -> ESSLNGA, PIADINERIA -> PDNRIA)
            core = tok[0] + re.sub(r"[AEIOU]", "", tok[1:-1]) + tok[-1]
            out.append(core[:8])
    return " ".join(out)


