def synthesize_4_variations(country: str, clean_name: str, category: str, idx: int) -> list[dict]:
    """Generate 4 realistic noisy bank statement descriptions (at least 2 truncated)."""
    v_vowel = truncate_vowels(clean_name)
    v_slice = truncate_prefix_slice(clean_name)

    d1 = f"{(idx % 28) + 1:02d}/{((idx % 11) + 1):02d}"
    d2 = f"{((idx + 7) % 28) + 1:02d}.{((idx + 3) % 11) + 1:02d}"
    d3 = f"{((idx + 13) % 28) + 1:02d}/{((idx + 5) % 11) + 1:02d}"
    d4 = f"{((idx + 19) % 28) + 1:02d}/{((idx + 8) % 11) + 1:02d}"

    id1 = f"AUT {(100000 + idx * 7919) % 900000 + 100000}"
    id2 = f"ID {(10000 + idx * 3571) % 90000 + 10000}A"
    id3 = f"TX{(10000 + idx * 6151) % 90000 + 10000}"
    id4 = f"REF {(100000 + idx * 4999) % 900000 + 100000}"

    if country == "IT":
        c1 = IT_CITIES[idx % len(IT_CITIES)]
        c2 = IT_CITIES[(idx + 3) % len(IT_CITIES)]
        c3 = IT_CITIES[(idx + 6) % len(IT_CITIES)]
        if category == "Utilities":
            p = IT_UTILITY_PREFIXES
            lines = [
                f"{p[0]} {d1} {v_vowel} SPA BOLLETTA {c1} {id1}",
                f"{p[1]} {d2} {clean_name} FATTURA {c2} {id4}",
                f"{p[2]} {d3} {v_slice} {v_vowel} ITALIA MND {id2}",
                f"{p[3]} {d4} {clean_name} ADDEBITO PERIODICO {c3} {id3}",
            ]
        else:
            p = IT_CARD_PREFIXES
            lines = [
                f"{p[idx % len(p)]} {d1} {v_vowel} {c1} {id1}",
                f"{p[(idx + 1) % len(p)]} {d2} {clean_name} {c2} {id2}",
                f"{p[(idx + 2) % len(p)]} {d3} {v_slice} {v_vowel} {c3} {id3}",
                f"{p[(idx + 3) % len(p)]} {d4} {clean_name} SRL {c1} {id4}",
            ]
    else:
        c1 = ES_CITIES[idx % len(ES_CITIES)]
        c2 = ES_CITIES[(idx + 3) % len(ES_CITIES)]
        c3 = ES_CITIES[(idx + 6) % len(ES_CITIES)]
        if category == "Utilities":
            p = ES_UTILITY_PREFIXES
            lines = [
                f"{p[0]} {d1} {v_vowel} SA FACTURA {c1} {id4}",
                f"{p[1]} {d2} {clean_name} MANDATO SEPA {c2} {id1}",
                f"{p[2]} {d3} {v_slice} {v_vowel} SUMINISTRO {c3} {id2}",
                f"{p[3]} {d4} {clean_name} ESPANA {c1} {id3}",
            ]
        else:
            p = ES_CARD_PREFIXES
            lines = [
                f"{p[idx % len(p)]} {d1} {v_vowel} {c1} {id1}",
                f"{p[(idx + 1) % len(p)]} {d2} {clean_name} {c2} {id2}",
                f"{p[(idx + 2) % len(p)]} {d3} {v_slice} {v_vowel} {c3} {id3}",
                f"{p[(idx + 3) % len(p)]} {d4} {clean_name} SL {c1} {id4}",
            ]

    return [{"Noisy_Description": line.upper(), "Target_Category": category} for line in lines]


def main():
    rows = []
    synthetic_rows = []
    idx = 0
    for country, cat_dict in [("IT", IT_POIS), ("ES", ES_POIS)]:
        seen = set()
        country_count = 0
        for category, names in cat_dict.items():
            for raw in names:
                clean = normalize(raw)
                if clean in seen:
                    raise ValueError(f"Duplicate POI in {country}: {clean}")
                seen.add(clean)
                rows.append({"Country": country, "Clean_Name": clean, "Category": category})
                synthetic_rows.extend(synthesize_4_variations(country, clean, category, idx))
                country_count += 1
                idx += 1
        print(f"Country {country}: {country_count} unique POIs verified.")
        assert country_count == 500, f"Expected 500 for {country}, got {country_count}"

    with open("clean_anchors_it_es.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["Country", "Clean_Name", "Category"])
        writer.writeheader()
        writer.writerows(rows)

    with open("myspendlens_synthetic_training_it_es.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["Noisy_Description", "Target_Category"])
        writer.writeheader()
        writer.writerows(synthetic_rows)

    print(f"Successfully wrote {len(rows)} total unique POIs to clean_anchors_it_es.csv")
    print(f"Successfully wrote {len(synthetic_rows)} synthetic rows to myspendlens_synthetic_training_it_es.csv")


if __name__ == "__main__":
    main()
